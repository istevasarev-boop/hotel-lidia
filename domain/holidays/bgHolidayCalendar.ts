export function getBulgarianHolidayInfo(date: string): BulgarianHolidayInfo | null {
  const exact = HOLIDAYS_2026[date];
  if (exact) return exact;

  const fixedName = FIXED_HOLIDAYS[date.slice(5)];
  return fixedName ? holiday(date, fixedName) : null;
}

function holiday(date: string, holidayName: string, leaveIdeaText?: string): BulgarianHolidayInfo {
  return {
    date,
    holidayName,
    isOfficialHoliday: true,
    leaveIdeaText,
    sourceLabel: leaveIdeaText ? SOURCE_LABEL : undefined
  };
}
